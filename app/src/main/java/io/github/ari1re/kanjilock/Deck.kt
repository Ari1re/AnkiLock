package io.github.ari1re.kanjilock

import android.content.Context
import org.json.JSONArray

enum class EntryType(val key: String, val label: String) {
    KANJI("kanji", "Kanji"),
    WORD("word", "Words"),
    PHRASE("phrase", "Phrases"),
    ANKI("anki", "Anki");

    companion object {
        val dictionaryTypes = listOf(KANJI, WORD, PHRASE)
        fun of(key: String): EntryType? = entries.firstOrNull { it.key == key }
    }
}

/** One card: shown big on the widget / lock screen card. */
data class Entry(
    val id: String,
    val type: EntryType,
    val level: Int,          // JLPT N-level (5..1); 0 for Anki cards
    val text: String,        // the kanji / word / phrase
    val reading: String,     // kana reading(s)
    val romaji: String,
    val meaning: String,
    val example: List<Token>,
    val exampleEn: String,
    val tag: String,         // "N5 · Kanji" or the Anki deck name
)

/** The built-in JLPT dictionary (assets/entries.json, generated by tools/build_data.py). */
object Deck {
    @Volatile private var cache: List<Entry>? = null

    fun all(ctx: Context): List<Entry> = cache ?: synchronized(this) {
        cache ?: load(ctx).also { cache = it }
    }

    private fun load(ctx: Context): List<Entry> {
        val json = ctx.assets.open("entries.json").bufferedReader(Charsets.UTF_8).use { it.readText() }
        val arr = JSONArray(json)
        return (0 until arr.length()).mapNotNull { i ->
            val o = arr.getJSONObject(i)
            val type = EntryType.of(o.getString("type")) ?: return@mapNotNull null
            val level = o.getInt("level")
            Entry(
                id = o.getString("id"),
                type = type,
                level = level,
                text = o.getString("text"),
                reading = o.getString("reading"),
                romaji = o.getString("romaji"),
                meaning = o.getString("meaning"),
                example = TokenParser.parse(o.getString("ex")),
                exampleEn = o.getString("exEn"),
                tag = "N$level · ${type.label}",
            )
        }
    }
}
